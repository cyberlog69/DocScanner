#!/usr/bin/env bash
# Rotates the DocScanner release key with an APK Signature Scheme v3 lineage.
#
# The retired key stays in the chain so existing installs update in place:
#   * API 28+ follows the lineage and adopts the new key.
#   * API 24-27 verify the v2 signature made with the retired key.
#
# The old keystore can be recovered from history if it is no longer on disk:
#   git show c3dfc9c:app/docscanner-signing.keystore > old.keystore
#
# Usage:
#   ./scripts/rotate-release-key.sh <old-keystore> <old-store-password> [alias] [new-keystore] [lineage]

set -euo pipefail

if [ "$#" -lt 1 ]; then
  echo "usage: $0 [old-keystore] <old-store-password> [alias] [new-keystore] [lineage]" >&2
  exit 1
fi

OLD_KEYSTORE="${1:-old.keystore}"
OLD_PASSWORD="${2:?usage: $0 [old-keystore] <old-store-password> [alias] [new-keystore] [lineage]}"
ALIAS="${3:-docscanner}"
NEW_KEYSTORE="${4:-app/release.keystore}"
LINEAGE="${5:-app/release-lineage.bin}"
OLD_KEYSTORE_GIT_REF="${OLD_KEYSTORE_GIT_REF:-c3dfc9c:app/docscanner-signing.keystore}"
DNAME="${DNAME:-CN=DocScanner, OU=Mobile, O=DocScanner, L=Unknown, ST=Unknown, C=IN}"

if [ ! -s "$OLD_KEYSTORE" ] || [ "$(head -c 1 "$OLD_KEYSTORE" | od -An -tx1 | tr -d ' \n')" != "30" ]; then
  echo "Recovering the retired keystore from $OLD_KEYSTORE_GIT_REF"
  git cat-file blob "$OLD_KEYSTORE_GIT_REF" > "$OLD_KEYSTORE"
fi
[ -s "$OLD_KEYSTORE" ] || { echo "Old keystore not found: $OLD_KEYSTORE" >&2; exit 1; }
[ ! -e "$NEW_KEYSTORE" ] || { echo "$NEW_KEYSTORE already exists. Move it aside first." >&2; exit 1; }
[ ! -e "$LINEAGE" ] || { echo "$LINEAGE already exists. Move it aside first." >&2; exit 1; }

SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ] && [ -f local.properties ]; then
  SDK="$(sed -n 's/^sdk\.dir=//p' local.properties | head -n 1)"
fi
if [ -z "$SDK" ]; then
  for candidate in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" "/usr/local/lib/android/sdk"; do
    if [ -d "$candidate/build-tools" ]; then SDK="$candidate"; break; fi
  done
fi
[ -n "$SDK" ] || { echo "Set ANDROID_HOME or ANDROID_SDK_ROOT (or add sdk.dir to local.properties)." >&2; exit 1; }

BUILD_TOOLS="$(find "$SDK/build-tools" -mindepth 1 -maxdepth 1 -type d -name '[0-9]*' | sort -V | tail -n 1)"
[ -n "$BUILD_TOOLS" ] || { echo "No build-tools found under $SDK" >&2; exit 1; }
APKSIGNER="$BUILD_TOOLS/apksigner"
if [ -n "${JAVA_HOME:-}" ] && [ -x "$JAVA_HOME/bin/keytool" ]; then
  KEYTOOL="$JAVA_HOME/bin/keytool"
else
  KEYTOOL="$(command -v keytool || true)"
  [ -n "$KEYTOOL" ] || { echo "No keytool found. Set JAVA_HOME or install a JDK." >&2; exit 1; }
fi

PASSWORD="$(LC_ALL=C tr -dc 'A-Za-z0-9_-' < /dev/urandom | head -c 32)"

mkdir -p "$(dirname "$NEW_KEYSTORE")"

"$KEYTOOL" -genkeypair -keystore "$NEW_KEYSTORE" -alias "$ALIAS" \
  -keyalg RSA -keysize 4096 -validity 10000 \
  -storepass "$PASSWORD" -keypass "$PASSWORD" -dname "$DNAME"

"$APKSIGNER" rotate --out "$LINEAGE" \
  --old-signer --ks "$OLD_KEYSTORE" --ks-key-alias "$ALIAS" --ks-pass "pass:$OLD_PASSWORD" \
  --new-signer --ks "$NEW_KEYSTORE" --ks-key-alias "$ALIAS" --ks-pass "pass:$PASSWORD"

umask 077
cat > keystore.properties <<EOF
# Generated by scripts/rotate-release-key.sh. Never commit this file.
storeFile=$NEW_KEYSTORE
storePassword=$PASSWORD
keyAlias=$ALIAS
keyPassword=$PASSWORD
EOF

OLD_FULL="$(cd "$(dirname "$OLD_KEYSTORE")" && pwd)/$(basename "$OLD_KEYSTORE")"
NEW_FULL="$(cd "$(dirname "$NEW_KEYSTORE")" && pwd)/$(basename "$NEW_KEYSTORE")"
LINEAGE_FULL="$(cd "$(dirname "$LINEAGE")" && pwd)/$(basename "$LINEAGE")"

echo
echo "New keystore: $NEW_KEYSTORE"
echo "Lineage:      $LINEAGE"
echo "Password:     $PASSWORD"
echo
echo "Back up the keystore, the lineage and the password. Losing them blocks future updates."
echo
echo "Upload the signing secrets:"
echo "  base64 -w0 '$NEW_FULL' | gh secret set DOCSCANNER_KEYSTORE_BASE64"
echo "  base64 -w0 '$OLD_FULL' | gh secret set DOCSCANNER_OLD_KEYSTORE_BASE64"
echo "  base64 -w0 '$LINEAGE_FULL' | gh secret set DOCSCANNER_LINEAGE_BASE64"
echo "  gh secret set DOCSCANNER_KEY_ALIAS --body '$ALIAS'"
echo "  gh secret set DOCSCANNER_OLD_STORE_PASSWORD --body '<old keystore password>'"
echo "  gh secret set DOCSCANNER_STORE_PASSWORD --body '$PASSWORD'"
echo "  gh secret set DOCSCANNER_KEY_PASSWORD --body '$PASSWORD'"
